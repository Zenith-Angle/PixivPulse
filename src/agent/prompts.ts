import type { DashboardData } from "../domain/types";

export function suggestedQuestions(data: DashboardData): Record<string, string[]> {
  const categories: Record<string, string[]> = {
    "快速判断": [
      "用现有数据简述作品数量、总浏览和总收藏，指出统计时间，不需要逐件列出。",
      "给我一份精简作品集体检：增长前三、粉丝变化、最值得跟进的问题；优先使用聚合简报。",
      "收藏贡献是否集中在少数作品？比较收藏前五与全作品总收藏，列出占比和风险。",
    ],
    "转化与表现": [
      "比较浏览至少 500 的作品中收藏率最高的前五件，列出浏览、收藏和收藏率；说明小样本偏差。",
      "分别列出浏览前五和收藏率前五，判断高曝光与高转化是否一致；不推断推荐流量。",
      "哪些作品值得进一步观察？结合浏览、收藏、点赞，区分数据事实与创作建议。",
      "评论最多的前五件作品是谁？与浏览和收藏比较，不把评论数等同于口碑。",
    ],
    "数据可信度": [
      "检查采样覆盖、最近更新时间、缺失指标和失败采集，说明目前不能回答哪些问题。",
      "目前保留的数据能否支持日增长比较？解释实际观测间隔与压缩采样的限制。",
      "哪些作品已不在最近列表中？说明缺席标记与删除、下架之间不能直接画等号。",
    ],
  };
  if (data.samples.length) categories["增长变化"] = [
    "比较最近 24 小时浏览增长前三和收藏增长前三，列出实际基线时间，排除无可比基线作品。",
    "在最近 7 天的可用观测范围中，哪些作品增长最快？明确实际覆盖和新作品缺失基线。",
    "找出观测期内浏览增长最多的作品，只查看这件作品的必要历史，判断增长是否持续。",
    "比较最近 24 小时增长前三件作品的浏览与收藏变化，不把差值误写成每日平均。",
  ];
  if (new Set(data.works.map(work => work.contentType ?? work.type)).size > 1) categories["内容结构"] = [
    "按内容类型汇总作品数、浏览、收藏和加权收藏率，说明作品数量和发布时间的可比性限制。",
    "不同内容类型的表现差异是否足以支持调整创作比例？先比较聚合指标，再列出仍需验证的假设。",
  ];
  if (data.works.some(work => work.seriesTitle)) (categories["内容结构"] ??= []).push(
    "按系列汇总作品数、浏览、收藏和加权收藏率，将未归入系列单列；不要平均各篇收藏率。",
    "比较表现靠前系列的规模与转化，判断优势可能来自作品数量还是单篇表现，避免因果断言。",
  );
  if (data.accountFollowerSamples?.some(row => row.accountId === data.settings.boundAccount?.id)) categories["粉丝观察"] = [
    "汇总最近 24 小时粉丝净变化和实际观测时间，说明未覆盖区间。",
    "最近 7 天粉丝净变化与作品增长是否同步？仅讨论相关信号，不声称某件作品带来了这些粉丝。",
    "当前粉丝数据能否区分新增关注与取消关注？说明净变化的含义和数据边界。",
  ];
  if (data.works.some(work => work.type === "novel")) {
    categories["原文采样"] = [
      "正文优先：选择 2–3 篇不同系列或篇幅的作品，一次读取多位置片段。先区分故事、章节与公告，再分析题材、角色目标、关系推进和叙事机制；每条判断注明片段依据，不先查粉丝历史。",
      "正文优先：选择一篇小说，深入阅读开头、中段和结尾采样。分别列出已观察事实、待验证假设、未知内容，给出三项对应具体位置的编辑建议，不续写。",
      "从正文采样判断作品承诺了什么阅读体验，哪些地方兑现了这个承诺，哪些信息还不足。先用原文证据，指标只作必要补充。",
      "选择两篇体裁与篇幅相近的小说比较正文，再用最少浏览和收藏指标辅助判断；列出相反证据，不因单篇表现就认定读者偏好。",
    ];
    categories["角色与叙事"] = [
      "阅读代表作品的正文片段，梳理人物目标、主动选择、阻力与关系变化。将角色设定标签和正文实际行动区分开，指出证据不足处。",
      "从正文片段检查叙事机制：情境规则、冲突建立、信息揭示、推进与回报是否连贯。只作非露骨的结构分析，不扩写具体情节。",
      "采样开头，判断信息交代、叙事视角与进入主要冲突前的铺垫是否匹配作品目标；给出保留与精简的理由。",
      "比较中段与末段采样的节奏、对白和描写比例，分析重复是否有叙事功能；不要把片段之间的空白当作剧情漏洞。",
    ];
    categories["创作决策"] = [
      "根据 2–3 篇正文采样，列出可保留的创作特点与一个值得尝试的新方向。每项包括原文依据、反例或不确定性、小规模试验方式，不将少量样本当作全库结论。",
      "结合正文和必要的作品指标，提出下一次投稿可验证的三个小改动；分别说明改哪里、为什么、预期观察什么，不承诺增长。",
      "先读取不同文体投稿的正文，再判断哪些作品适合相互比较；公告、说明与故事分开讨论，避免平均成统一创作风格。",
    ];
  }
  return categories;
}
